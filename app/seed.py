def parse_time(value):
    hour, minute = map(int, value.split(":"))
    return time(hour, minute)


def seed_database():
    db = session()

    try:
        for field, schedules in SCHEDULES.items():

            for day, subject, teachers, start, end in schedules:

                # ساخت دبیرها در صورت نبودن
                teacher_objects = []

                for teacher_name in teachers:
                    teacher = (
                        db.query(Teacher)
                        .filter(
                            Teacher.name == teacher_name,
                            Teacher.subject == subject,
                            Teacher.field == field,
                        )
                        .first()
                    )

                    if teacher is None:
                        teacher = Teacher(
                            name=teacher_name,
                            subject=subject,
                            field=field,
                        )
                        db.add(teacher)
                        db.flush()

                    teacher_objects.append(teacher)

                # ساخت کلاس برای هر دبیر
                for teacher in teacher_objects:

                    exists = (
                        db.query(Class)
                        .filter(
                            Class.teacher_id == teacher.id,
                            Class.day_of_week == DAY_TO_NUM[day],
                            Class.start_time == parse_time(start),
                            Class.end_time == parse_time(end),
                        )
                        .first()
                    )

                    if exists:
                        continue

                    new_class = Class(
                        teacher_id=teacher.id,
                        subject=subject,
                        field=field,
                        day_of_week=DAY_TO_NUM[day],
                        start_time=parse_time(start),
                        end_time=parse_time(end),
                        title=subject,
                        source="seed",
                    )

                    db.add(new_class)

        db.commit()
        print("✅ برنامه درسی با موفقیت وارد دیتابیس شد.")

    except Exception:
        db.rollback()
        raise

    finally:
        db.close()


if __name__ == "__main__":
    seed_database()
