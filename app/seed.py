def parse_time(value):
    hour, minute = map(int, value.split(":"))
    return time(hour, minute)


def seed_database():
    db = session()

    try:
        for field, schedules in SCHEDULES.items():

            for day, subject, teachers, start, end in schedules:

                start_time = parse_time(start)
                end_time = parse_time(end)
                day_number = DAY_TO_NUM[day]

                for teacher_name in teachers:

                    # پیدا کردن دبیر موجود
                    teacher = (
                        db.query(Teacher)
                        .filter(
                            Teacher.name == teacher_name,
                            Teacher.subject == subject,
                            Teacher.field == field,
                        )
                        .first()
                    )

                    # اگر وجود نداشت، ایجادش کن
                    if teacher is None:
                        teacher = Teacher(
                            name=teacher_name,
                            subject=subject,
                            field=field,
                        )

                        db.add(teacher)
                        db.flush()

                    # بررسی کلاس تکراری
                    existing_class = (
                        db.query(Class)
                        .filter(
                            Class.teacher_id == teacher.id,
                            Class.day_of_week == day_number,
                            Class.start_time == start_time,
                            Class.end_time == end_time,
                        )
                        .first()
                    )

                    # اگر قبلاً وجود دارد، دوباره نساز
                    if existing_class:
                        continue

                    # ایجاد کلاس
                    new_class = Class(
                        teacher_id=teacher.id,
                        subject=subject,
                        field=field,
                        day_of_week=day_number,
                        start_time=start_time,
                        end_time=end_time,
                        title=subject,
                        source="seed",
                    )

                    db.add(new_class)

        db.commit()

        print("✅ تمام دبیرها و برنامه‌های درسی وارد دیتابیس شدند.")

    except Exception:
        db.rollback()
        raise

    finally:
        db.close()


if __name__ == "__main__":
    seed_database()
